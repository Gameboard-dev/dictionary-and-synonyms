"""Writes THIRD-PARTY-LICENSES.txt, the third-party licences of Dictionary and Synonyms, at the repository's root. Run it
from anywhere, with Python 3.8+ and cargo-about (`cargo install cargo-about --locked --features cli`), after any change
to the workspace's Cargo.lock:

    python licences/generate.py

The file has three parts:
  1. the Rust crates compiled into the plugin (main.js holds the WebAssembly module), with their licence texts
     (cargo-about, about.toml and about.hbs);
  2. the COPYRIGHT, AUTHORS and NOTICE files those crates' packages carry, copied in full;
  3. data.txt: the dictionaries and services the plugin reads from (none is shipped with it), their licences and the
     attribution they ask for (kept by hand; check it when a source changes).

cargo-about fails, and nothing is written, if a crate's licence is not in about.toml's `accepted` list.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PLUGIN = os.path.dirname(HERE)
OUT = os.path.join(PLUGIN, "THIRD-PARTY-LICENSES.txt")
NOTICE_PREFIXES = ("NOTICE", "COPYRIGHT", "AUTHORS", "THIRD-PARTY", "THIRD_PARTY")

HEADER = """THIRD-PARTY LICENCES: Dictionary and Synonyms, an Obsidian plugin (main.js, which holds the WebAssembly module)

Dictionary and Synonyms is released under the MIT licence; its text is in the file LICENSE beside this one. The source
code is at https://github.com/Gameboard-dev/dictionary-and-synonyms (each release has its tag), and the build tool and
shared crate at https://github.com/Gameboard-dev/obsidian-cargo-lib.

This file lists the work of others that the plugin contains, with the licence texts and copyright notices their licences
ask to be passed on (Parts 1 and 2), and the sources of the words it shows, with their licences (Part 3). It was
generated by licences/generate.py with cargo-about, for wasm32-unknown-unknown.

"""


def cargo_about(*args):
    cmd = ["cargo", "about", "generate", "--fail", "--locked", "-c", os.path.join(HERE, "about.toml"),
           "-m", os.path.join(PLUGIN, "core", "Cargo.toml"), "--target", "wasm32-unknown-unknown", *args]
    run = subprocess.run(cmd, cwd=PLUGIN, capture_output=True, text=True, encoding="utf-8")
    if run.returncode != 0:
        sys.exit(f"cargo about failed (exit {run.returncode}):\n{run.stderr}")
    return run.stdout


def notices(listing):
    """Part 2: every COPYRIGHT, AUTHORS or NOTICE file in the packages of the crates cargo-about listed."""
    out, seen = [], set()
    for krate in sorted(listing["crates"], key=lambda c: (c["package"]["name"], c["package"]["version"])):
        pkg = krate["package"]
        key = (pkg["name"], pkg["version"])
        if key in seen:
            continue
        seen.add(key)
        root = os.path.dirname(pkg["manifest_path"])
        try:
            names = sorted(os.listdir(root))
        except OSError:
            continue
        for name in names:
            path = os.path.join(root, name)
            if not name.upper().startswith(NOTICE_PREFIXES) or not os.path.isfile(path):
                continue
            with open(path, encoding="utf-8", errors="replace") as f:
                text = f.read().strip("\n")
            out.append(f"{'=' * 80}\n{pkg['name']} {pkg['version']}: {name}\n{'-' * 80}\n{text}\n\n")
    head = ("PART 2. COPYRIGHT, AUTHORS AND NOTICE FILES\n\n"
            "The COPYRIGHT, AUTHORS and NOTICE files in the packages of the crates in Part 1, in full. No crate here ships\n"
            "an Apache-2.0 NOTICE file unless one is listed below.\n\n")
    return head + ("".join(out) if out else "None of the crates in Part 1 carries such a file.\n\n")


def main():
    with open(os.path.join(HERE, "data.txt"), encoding="utf-8") as f:
        data = f.read()
    body = cargo_about(os.path.join(HERE, "about.hbs"))
    listing = json.loads(cargo_about("--format", "json"))
    text = HEADER + body.strip("\n") + "\n\n\n" + notices(listing) + "\n" + data
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"THIRD-PARTY-LICENSES.txt: {len(listing['crates'])} crates, {len(text) // 1024} KB")


if __name__ == "__main__":
    main()
